def normalize_cell(raw: Optional[str]) -> str:
    value = (raw or "").strip()
    return "" if value.upper() in MISSING_TOKENS else value


def normalize_row_id(raw: Optional[str]) -> str:
    value = normalize_cell(raw)
    if not value:
        raise ValueError("发现空row_id")
    return value


def row_id_sort_key(value: str) -> Tuple[int, object]:
    digits = "".join(character for character in value if character.isdigit())
    if digits:
        return 0, int(digits)
    return 1, value


def parse_float(value: str, field: str, row_id: str) -> Optional[float]:
    value = normalize_cell(value)
    if not value:
        return None
    lowered = value.lower()
    if lowered == "true":
        return 1.0
    if lowered == "false":
        return 0.0
    try:
        number = float(value)
    except ValueError:
        raise ValueError(
            "字段{}在row_id={}中不是数值：{!r}".format(field, row_id, value)
        )
    if not math.isfinite(number):
        raise ValueError(
            "字段{}在row_id={}中不是有限数值：{!r}".format(field, row_id, value)
        )
    return number


def normalize_numeric(value: str, field: str, row_id: str) -> str:
    number = parse_float(value, field, row_id)
    if number is None:
        return ""
    if number == 0:
        return "0"
    return "{:.15g}".format(number)


def format_number(number: float) -> str:
    if number == 0:
        return "0"
    return "{:.15g}".format(number)


def parse_iso_day(value: str, filename: str, row_id: str) -> date:
    try:
        return date.fromisoformat(value)
    except ValueError:
        raise ValueError(
            "{}中row_id={}的date不是YYYY-MM-DD：{!r}".format(
                filename, row_id, value
            )
        )


def read_quarter(
    path: Path,
    start_text: str,
    end_text: str,
    expected_rows: int,
    reference_fields: Optional[List[str]],
) -> Tuple[List[str], List[Dict[str, str]]]:
    start_day = date.fromisoformat(start_text)
    end_day = date.fromisoformat(end_text)
    rows: List[Dict[str, str]] = []

    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fields = list(reader.fieldnames or [])
        if not fields:
            raise ValueError("CSV没有表头：{}".format(path.name))
        if len(fields) != len(set(fields)):
            raise ValueError("CSV存在重复字段名：{}".format(path.name))
        if reference_fields is not None and fields != reference_fields:
            missing = [field for field in reference_fields if field not in fields]
            extra = [field for field in fields if field not in reference_fields]
            raise ValueError(
                "{}与其他季度字段或顺序不一致；缺少={}，新增={}".format(
                    path.name, missing, extra
                )
            )

        for line_number, source_row in enumerate(reader, start=2):
            if None in source_row:
                raise ValueError(
                    "{}第{}行列数超过表头".format(path.name, line_number)
                )
            clean = {
                field: normalize_cell(source_row.get(field)) for field in fields
            }
            row_id = normalize_row_id(clean.get("row_id"))
            clean["row_id"] = row_id
            row_day = parse_iso_day(clean.get("date", ""), path.name, row_id)
            if not (start_day <= row_day < end_day):
                raise ValueError(
                    "{}中row_id={}的日期{}不在[{}, {})内".format(
                        path.name, row_id, row_day, start_text, end_text
                    )
                )
            target = parse_float(
                clean.get("average_value", ""), "average_value", row_id
            )
            if target is None or target <= 0:
                raise ValueError(
                    "row_id={}的average_value必须为正数".format(row_id)
                )
            rows.append(clean)

    if len(rows) != expected_rows:
        raise ValueError(
            "{}应有{}行，实际为{}行".format(
                path.name, expected_rows, len(rows)
            )
        )
    return fields, rows


def write_csv(
    path: Path, fields: Sequence[str], rows: Iterable[Dict[str, str]]
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=list(fields),
            extrasaction="ignore",
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)


def field_profile(
    rows: Sequence[Dict[str, str]], fields: Sequence[str]
) -> Dict[str, Dict[str, object]]:
    profile: Dict[str, Dict[str, object]] = {}
    for field in fields:
        values: Set[str] = set()
        nonmissing = 0
        for row in rows:
            value = normalize_cell(row.get(field))
            if value:
                nonmissing += 1
                values.add(value)
        profile[field] = {
            "nonmissing": nonmissing,
            "missing": len(rows) - nonmissing,
            "unique_nonmissing": len(values),
        }
    return profile


def validate_merged_rows(
    rows: Sequence[Dict[str, str]], fields: Sequence[str]
) -> None:
    if len(fields) != EXPECTED_RAW_FIELDS:
        raise ValueError(
            "脚本09原始表应为{}列，实际为{}列".format(
                EXPECTED_RAW_FIELDS, len(fields)
            )
        )
    if fields[:len(BASE_FIELDS)] != BASE_FIELDS:
        raise ValueError(
            "前15个基础字段与脚本09不一致：{}".format(
                fields[:len(BASE_FIELDS)]
            )
        )
    if len(rows) != EXPECTED_TOTAL_ROWS:
        raise ValueError(
            "合并后应为{}行，实际为{}行".format(
                EXPECTED_TOTAL_ROWS, len(rows)
            )
        )

    row_ids: Set[str] = set()
    site_days: Set[Tuple[str, str]] = set()
    for row in rows:
        row_id = row["row_id"]
        site_day = (row.get("area", ""), row.get("date", ""))
        if row_id in row_ids:
            raise ValueError("发现重复row_id：{}".format(row_id))
        if site_day in site_days:
            raise ValueError("发现重复(area,date)：{}".format(site_day))
        row_ids.add(row_id)
        site_days.add(site_day)

        start_ms = parse_float(
            row.get("local_day_start_utc_ms", ""),
            "local_day_start_utc_ms", row_id,
        )
        end_ms = parse_float(
            row.get("local_day_end_utc_ms", ""),
            "local_day_end_utc_ms", row_id,
        )
        if start_ms is None or end_ms is None:
            raise ValueError("row_id={}的本地日时间戳为空".format(row_id))
        if abs((end_ms - start_ms) - EXPECTED_DAY_MILLISECONDS) > 0.5:
            raise ValueError("row_id={}的本地日不是24小时".format(row_id))

        support = parse_float(
            row.get("spatial_support_m", ""), "spatial_support_m", row_id
        )
        if support is None or abs(support - EXPECTED_BUFFER_M) > 1e-9:
            raise ValueError("row_id={}的空间支持不是300米".format(row_id))

    sites = {row.get("area", "") for row in rows}
    dates = {row.get("date", "") for row in rows}
    if len(sites) != EXPECTED_SITE_COUNT:
        raise ValueError(
            "应有{}个地点，实际为{}个".format(EXPECTED_SITE_COUNT, len(sites))
        )
    if len(dates) != EXPECTED_DATE_COUNT:
        raise ValueError(
            "应有{}个日期，实际为{}个".format(EXPECTED_DATE_COUNT, len(dates))
        )
    if min(dates) != EXPECTED_MIN_DATE or max(dates) != EXPECTED_MAX_DATE:
        raise ValueError(
            "日期范围异常：{}至{}".format(min(dates), max(dates))
        )


def availability_flag(row: Dict[str, str], source_field: str) -> str:
    return "1" if normalize_cell(row.get(source_field)) else "0"


def target_range_flag(row: Dict[str, str]) -> str:
    row_id = row["row_id"]
    least = parse_float(row.get("least_value", ""), "least_value", row_id)
    average = parse_float(
        row.get("average_value", ""), "average_value", row_id
    )
    maximum = parse_float(row.get("max_value", ""), "max_value", row_id)
    if least is None or average is None or maximum is None:
        return ""
    return "0" if least <= average <= maximum else "1"


def build_ml_row(
    row: Dict[str, str], source_candidate_fields: Sequence[str]
) -> Dict[str, str]:
    row_id = row["row_id"]
    row_day = date.fromisoformat(row["date"])
    first_day = date.fromisoformat(EXPECTED_MIN_DATE)
    target = parse_float(row["average_value"], "average_value", row_id)
    assert target is not None
    day_of_year = row_day.timetuple().tm_yday
    angle = 2.0 * math.pi * (day_of_year - 1) / 365.2425

    output: Dict[str, str] = {
        "row_id": row_id,
        "area": row.get("area", ""),
        "date": row["date"],
        "average_value": normalize_numeric(
            row["average_value"], "average_value", row_id
        ),
        "target_log1p": format_number(math.log1p(target)),
        "longitude": normalize_numeric(
            row.get("longitude", ""), "longitude", row_id
        ),
        "latitude": normalize_numeric(
            row.get("latitude", ""), "latitude", row_id
        ),
        "target_range_inconsistent": target_range_flag(row),
        "year": str(row_day.year),
        "month": str(row_day.month),
        "day_of_year": str(day_of_year),
        "days_since_start": str((row_day - first_day).days),
        "doy_sin": format_number(math.sin(angle)),
        "doy_cos": format_number(math.cos(angle)),
    }

    for field in source_candidate_fields:
        value = normalize_numeric(row.get(field, ""), field, row_id)
        if field == "landsat_lst_c" and value:
            lst = float(value)
            if lst < LANDSAT_LST_MIN_C or lst > LANDSAT_LST_MAX_C:
                value = ""
        output[field] = value

    for flag_field, source_field in AVAILABILITY_SOURCES.items():
        output[flag_field] = availability_flag(row, source_field)

    raw_landsat = parse_float(
        row.get("landsat_lst_c", ""), "landsat_lst_c", row_id
    )
    output["landsat_lst_outlier_flag"] = (
        "1" if raw_landsat is not None and (
            raw_landsat < LANDSAT_LST_MIN_C
            or raw_landsat > LANDSAT_LST_MAX_C
        ) else "0"
    )

    exact_available = normalize_cell(row.get("hls_exact_ndvi")) != ""
    for index_name in HLS_INDEX_NAMES:
        exact = normalize_cell(row.get("hls_exact_{}".format(index_name)))
        near = normalize_cell(row.get("hls_near_{}".format(index_name)))
        chosen = exact if exact else near
        output["hls_model_{}".format(index_name)] = normalize_numeric(
            chosen, "hls_model_{}".format(index_name), row_id
        )

    signed_gap = parse_float(
        row.get("hls_near_signed_gap_days_mean", ""),
        "hls_near_signed_gap_days_mean", row_id,
    )
    abs_gap = parse_float(
        row.get("hls_near_abs_gap_days_mean", ""),
        "hls_near_abs_gap_days_mean", row_id,
    )
    if exact_available:
        model_signed_gap = 0.0
        model_abs_gap = 0.0
        source_future = 0
    else:
        model_signed_gap = signed_gap
        model_abs_gap = abs_gap
        source_future = 1 if signed_gap is not None and signed_gap > 0 else 0

    output["hls_model_signed_gap_days"] = (
        "" if model_signed_gap is None else format_number(model_signed_gap)
    )
    output["hls_model_abs_gap_days"] = (
        "" if model_abs_gap is None else format_number(model_abs_gap)
    )
    output["hls_model_source_exact"] = "1" if exact_available else "0"
    output["hls_model_source_future"] = str(source_future)
    return output


def count_missing(
    rows: Sequence[Dict[str, str]], fields: Sequence[str]
) -> Dict[str, int]:
    result = defaultdict(int)  # type: Dict[str, int]
    for field in fields:
        for row in rows:
            if not normalize_cell(row.get(field)):
                result[field] += 1
    return dict(result)


def assert_fields_exist(fields: Sequence[str], required: Sequence[str]) -> None:
    missing = [field for field in required if field not in fields]
    if missing:
        raise ValueError("生成表缺少必要字段：{}".format(missing))


def assert_complete(
    rows: Sequence[Dict[str, str]], fields: Sequence[str], label: str
) -> None:
    for row in rows:
        for field in fields:
            if not normalize_cell(row.get(field)):
                raise ValueError(
                    "{}不是完整数据集：row_id={}的{}为空".format(
                        label, row.get("row_id", ""), field
                    )
                )


def write_feature_sets(
    path: Path,
    ml_fields: Sequence[str],
    dropped_no_information: Sequence[str],
) -> None:
    sparse_groups = {
        group: [field for field in fields if field in ml_fields]
        for group, fields in SPARSE_EXTENSION_GROUPS.items()
    }
    payload = {
        "schema_version": "2.0",
        "target_raw": "average_value",
        "target_recommended": "target_log1p",
        "identifier": "row_id",
        "site_group": "area",
        "time_group": "date",
        "metadata_not_predictors": list(ML_METADATA_FIELDS),
        "dense_core_retrospective_features": DENSE_RETROSPECTIVE_FEATURES,
        "strict_time_dense_features": STRICT_TIME_DENSE_FEATURES,
        "sparse_extension_groups": sparse_groups,
        "dropped_no_information_fields": list(dropped_no_information),
        "known_default_redundancies": [
            ["hls_model_ndmi", "hls_model_ndbi"],
            ["jrc_permanent_water", "jrc_distance_to_water_m"],
            ["hls_exact_available", "hls_gapfill_used"],
        ],
        "windowing_policy": {
            "window_created_during_merge": False,
            "reason": "Windowing must follow the outer site/time split to avoid leakage.",
            "common_comparison_rule": (
                "Use the same lookback, horizon, predictors and outer folds for "
                "all seven models. Flatten windows for RF/XGBoost/LightGBM/MLP; "
                "keep [samples, timesteps, features] for LSTM."
            ),
            "target_lags_for_remote_sensing_inversion": False,
            "future_hls_allowed_for_forecasting": False,
        },
    }
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def feature_role(
    field: str,
    dense_retro: Set[str],
    strict_dense: Set[str],
    sparse_lookup: Dict[str, str],
) -> str:
    roles: List[str] = []
    if field in dense_retro:
        roles.append("dense_retrospective")
    if field in strict_dense:
        roles.append("strict_time_dense")
    if field in sparse_lookup:
        roles.append("sparse_extension:{}".format(sparse_lookup[field]))
    if not roles:
        roles.append("optional_or_audit")
    return ";".join(roles)


def write_feature_profile(
    path: Path,
    ml_rows: Sequence[Dict[str, str]],
    candidate_fields: Sequence[str],
) -> None:
    profile = field_profile(ml_rows, candidate_fields)
    dense_retro = set(DENSE_RETROSPECTIVE_FEATURES)
    strict_dense = set(STRICT_TIME_DENSE_FEATURES)
    sparse_lookup: Dict[str, str] = {}
    for group, fields in SPARSE_EXTENSION_GROUPS.items():
        for field in fields:
            sparse_lookup[field] = group

    rows = []
    for field in candidate_fields:
        record = profile[field]
        missing = int(record["missing"])
        rows.append({
            "field": field,
            "role": feature_role(
                field, dense_retro, strict_dense, sparse_lookup
            ),
            "nonmissing_rows": str(record["nonmissing"]),
            "missing_rows": str(missing),
            "missing_percent": "{:.4f}".format(
                100.0 * missing / len(ml_rows)
            ),
            "unique_nonmissing": str(record["unique_nonmissing"]),
        })
    write_csv(
        path,
        [
            "field", "role", "nonmissing_rows", "missing_rows",
            "missing_percent", "unique_nonmissing",
        ],
        rows,
    )


def write_qa_report(
    path: Path,
    input_counts: Sequence[Tuple[str, int]],
    raw_fields: Sequence[str],
    raw_rows: Sequence[Dict[str, str]],
    ml_fields: Sequence[str],
    ml_rows: Sequence[Dict[str, str]],
    dropped_no_information: Sequence[str],
) -> None:
    target_flags = [
        row for row in ml_rows if row["target_range_inconsistent"] == "1"
    ]
    lst_flags = [
        row for row in ml_rows if row["landsat_lst_outlier_flag"] == "1"
    ]
    exact_count = sum(
        1 for row in ml_rows if row["hls_model_source_exact"] == "1"
    )
    gapfill_count = len(ml_rows) - exact_count
    future_gapfill = sum(
        1 for row in ml_rows if row["hls_model_source_future"] == "1"
    )
    over_16 = sum(
        1 for row in ml_rows
        if row["hls_model_source_exact"] == "0"
        and float(row["hls_model_abs_gap_days"]) > 16.0
    )
    over_32 = sum(
        1 for row in ml_rows
        if row["hls_model_source_exact"] == "0"
        and float(row["hls_model_abs_gap_days"]) > 32.0
    )

    candidate_fields = [
        field for field in ml_fields
        if field not in ML_METADATA_FIELDS and field not in TIME_FEATURE_FIELDS
    ] + list(TIME_FEATURE_FIELDS)
    missing = count_missing(ml_rows, candidate_fields)
    missing_over_50 = sum(
        1 for field in candidate_fields
        if missing.get(field, 0) / len(ml_rows) > 0.50
    )
    missing_over_90 = sum(
        1 for field in candidate_fields
        if missing.get(field, 0) / len(ml_rows) > 0.90
    )

    lines = [
        "Guangzhou Anion Script-09 Merge and ML QA Report v2",
        "=" * 62,
        "",
        "Input files:",
    ]
    for filename, count in input_counts:
        lines.append("  {}: {} rows".format(filename, count))
    lines.extend([
        "",
        "Raw merged table: {} rows x {} fields".format(
            len(raw_rows), len(raw_fields)
        ),
        "ML master table: {} rows x {} fields".format(
            len(ml_rows), len(ml_fields)
        ),
        "Sites: {}".format(len({row["area"] for row in raw_rows})),
        "Dates: {}".format(len({row["date"] for row in raw_rows})),
        "Date range: {} to {}".format(
            min(row["date"] for row in raw_rows),
            max(row["date"] for row in raw_rows),
        ),
        "Duplicate row_id: 0",
        "Duplicate (area, date): 0",
        "",
        "No-information source fields removed from ML master ({}):".format(
            len(dropped_no_information)
        ),
        "  {}".format(
            ", ".join(dropped_no_information)
            if dropped_no_information else "None"
        ),
        "",
        "ML candidate fields with >50% missing: {}".format(missing_over_50),
        "ML candidate fields with >90% missing: {}".format(missing_over_90),
        "Dense retrospective feature count: {} (complete rows: {})".format(
            len(DENSE_RETROSPECTIVE_FEATURES), len(ml_rows)
        ),
        "Strict-time dense feature count: {} (complete rows: {})".format(
            len(STRICT_TIME_DENSE_FEATURES), len(ml_rows)
        ),
        "",
        "HLS exact-day rows: {} ({:.2f}%)".format(
            exact_count, 100.0 * exact_count / len(ml_rows)
        ),
        "HLS nearest-gapfill rows: {} ({:.2f}%)".format(
            gapfill_count, 100.0 * gapfill_count / len(ml_rows)
        ),
        "HLS gapfill using future imagery: {} ({:.2f}% of gapfilled)".format(
            future_gapfill, 100.0 * future_gapfill / gapfill_count
        ),
        "HLS gapfill >16 days: {}".format(over_16),
        "HLS gapfill >32 days: {}".format(over_32),
        "",
        "Target range inconsistencies: {}".format(len(target_flags)),
    ])
    for row in target_flags:
        lines.append(
            "  {} | {} | {}".format(row["row_id"], row["area"], row["date"])
        )
    lines.append("Landsat LST outliers blanked only in ML table: {}".format(
        len(lst_flags)
    ))
    for row in lst_flags:
        lines.append(
            "  {} | {} | {}".format(row["row_id"], row["area"], row["date"])
        )
    lines.extend([
        "",
        "Methodology safeguards:",
        "- No imputation, scaling, balancing, sliding window or train/test split was performed.",
        "- Fit imputation/scaling/selection only inside each training fold.",
        "- Use area for leave-one-site-out validation and date for forward time validation.",
        "- Never use grade, remark, least_value, max_value or source_id_text as predictors.",
        "- Do not use area or raw coordinates in the default spatial-generalization model.",
        "- Nearest-HLS future sources are prohibited in forward forecasting.",
    ])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Merge six GEE script-09 quarterly CSV files and create validated "
            "ML master/core datasets without leakage-prone preprocessing."
        )
    )
    parser.add_argument(
        "--input-dir", type=Path, default=DEFAULT_DATA_DIR,
        help="Folder containing the six script-09 quarterly CSV files.",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=PACKAGE_PATHS.reproduced / "preprocessing",
        help="New output folder outside the project; default: ../NAI_reproduced/preprocessing.",
    )
    args = parser.parse_args()

    input_dir = args.input_dir.expanduser()
    if not input_dir.is_absolute():
        input_dir = PACKAGE_PATHS.root / input_dir
    input_dir = input_dir.resolve()
    output_dir = ensure_reproduction_output(args.output_dir, PACKAGE_PATHS.root)
    if not input_dir.is_dir():
        raise ValueError("找不到输入文件夹：{}".format(input_dir))

    paths = {
        "raw": output_dir / "GZ_anion_09_master_core_raw_merged.csv",
        "master": output_dir / "GZ_anion_09_master_core_ML_master_v2.csv",
        "dense_retro": output_dir / "GZ_anion_09_dense_core_retrospective_v2.csv",
        "strict_dense": output_dir / "GZ_anion_09_strict_time_dense_v2.csv",
        "feature_sets": output_dir / "GZ_anion_09_feature_sets_v2.json",
        "profile": output_dir / "GZ_anion_09_feature_profile_v2.csv",
        "qa": output_dir / "GZ_anion_09_merge_QA_v2.txt",
    }

    all_rows: List[Dict[str, str]] = []
    reference_fields: Optional[List[str]] = None
    input_counts: List[Tuple[str, int]] = []

    for filename, start_text, end_text, expected_rows in EXPECTED_FILES:
        file_path = input_dir / filename
        if not file_path.is_file():
            raise ValueError("缺少文件：{}".format(file_path))
        fields, rows = read_quarter(
            file_path, start_text, end_text, expected_rows, reference_fields
        )
        if reference_fields is None:
            reference_fields = fields
        all_rows.extend(rows)
        input_counts.append((filename, len(rows)))
        print("读取 {:>5} 行：{}".format(len(rows), filename))

    if reference_fields is None:
        raise ValueError("没有读取到任何CSV")
    validate_merged_rows(all_rows, reference_fields)

    all_rows.sort(
        key=lambda row: (
            row["date"], row.get("area", ""), row_id_sort_key(row["row_id"])
        )
    )
    write_csv(paths["raw"], reference_fields, all_rows)

    raw_predictor_fields = [
        field for field in reference_fields
        if field not in NON_PREDICTOR_RAW_FIELDS
    ]
    raw_profile = field_profile(all_rows, raw_predictor_fields)
    dropped_no_information = [
        field for field in raw_predictor_fields
        if int(raw_profile[field]["unique_nonmissing"]) <= 1
    ]
    source_candidate_fields = [
        field for field in raw_predictor_fields
        if field not in dropped_no_information
    ]

    ml_fields = (
        ML_METADATA_FIELDS
        + TIME_FEATURE_FIELDS
        + source_candidate_fields
        + DERIVED_FEATURE_FIELDS
    )
    if len(ml_fields) != len(set(ml_fields)):
        duplicates = sorted({
            field for field in ml_fields if ml_fields.count(field) > 1
        })
        raise ValueError("ML字段重复：{}".format(duplicates))

    ml_rows = [build_ml_row(row, source_candidate_fields) for row in all_rows]
    assert_fields_exist(ml_fields, DENSE_RETROSPECTIVE_FEATURES)
    assert_fields_exist(ml_fields, STRICT_TIME_DENSE_FEATURES)
    assert_complete(
        ml_rows, DENSE_RETROSPECTIVE_FEATURES, "历史反演稠密核心表"
    )
    assert_complete(
        ml_rows, STRICT_TIME_DENSE_FEATURES, "严格时间稠密表"
    )

    write_csv(paths["master"], ml_fields, ml_rows)

    view_metadata = list(ML_METADATA_FIELDS)
    dense_retro_fields = view_metadata + DENSE_RETROSPECTIVE_FEATURES
    strict_dense_fields = view_metadata + STRICT_TIME_DENSE_FEATURES
    write_csv(paths["dense_retro"], dense_retro_fields, ml_rows)
    write_csv(paths["strict_dense"], strict_dense_fields, ml_rows)

    candidate_profile_fields = [
        field for field in ml_fields if field not in ML_METADATA_FIELDS
    ]
    write_feature_sets(
        paths["feature_sets"], ml_fields, dropped_no_information
    )
    write_feature_profile(
        paths["profile"], ml_rows, candidate_profile_fields
    )
    write_qa_report(
        paths["qa"], input_counts, reference_fields, all_rows,
        ml_fields, ml_rows, dropped_no_information,
    )

    print("\n全部完成。未执行插补、标准化、滑窗或数据集划分。")
    print("原始合并表：{}行 x {}列".format(
        len(all_rows), len(reference_fields)
    ))
    print(paths["raw"])
    print("ML主表：{}行 x {}列".format(len(ml_rows), len(ml_fields)))
    print(paths["master"])
    print("历史反演稠密核心表：{}行 x {}列".format(
        len(ml_rows), len(dense_retro_fields)
    ))
    print(paths["dense_retro"])
    print("严格时间稠密表：{}行 x {}列".format(
        len(ml_rows), len(strict_dense_fields)
    ))
    print(paths["strict_dense"])
    print("字段集合：{}".format(paths["feature_sets"]))
    print("字段质量表：{}".format(paths["profile"]))
    print("QA报告：{}".format(paths["qa"]))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("\n处理失败：{}".format(exc))
