"""
Merge and quality-control the six quarterly CSV exports generated by
09_Master_core_products_quarterly.js.

Outputs
-------
1. GZ_anion_09_master_core_raw_merged.csv
   Exact 5,998 x 95 vertical merge. No source value is changed.

2. GZ_anion_09_master_core_ML_master_v2.csv
   Wide machine-learning master table. Obvious leakage/identifier fields are
   retained only as metadata, no-information predictor columns are removed,
   calendar/HLS coalesced/availability/QA fields are added, and physically
   implausible Landsat LST values outside [-10, 60] deg C are blanked only in
   this ML copy (the raw merged table remains unchanged).

3. GZ_anion_09_dense_core_retrospective_v2.csv
   A complete core feature view for OFFLINE historical reconstruction. It uses
   the nearest-valid HLS auxiliary values when exact-day HLS is unavailable.
   Some nearest HLS values come from dates after the target day, so this view
   must NOT be used as-is for causal/forward forecasting.

4. GZ_anion_09_strict_time_dense_v2.csv
   A complete dense view that excludes nearest-HLS auxiliary values. This is a
   safer starting point for strict time matching, but a true t+h forecast must
   still lag all dynamic predictors inside the modelling workflow.

5. Feature-set JSON, feature profile CSV, and QA report.

Compatible with Python 3.8.10. No third-party packages are required.

Important methodology
---------------------
This script deliberately does NOT create sliding windows, impute missing
values, standardize variables, balance samples, or split train/test data.
Those transformations must be fitted/constructed after defining each outer
validation fold, otherwise future dates or held-out sites can leak into model
training. A common window builder should later be reused by RF, XGBoost, MLP,
LightGBM and LSTM so their performance comparison uses the same information.
"""

